import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { resolveTheme, cssVariables, rgbChannels, mixColor, contrastRatio } from '../src/shared/theme/model/themeResolver.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const model = path.join(root, 'src/shared/theme/model');
const read = name => JSON.parse(fs.readFileSync(path.join(model, name), 'utf8'));
const manifest = read('manifest.json'), modes = read('modes.json');
const standard = createRequire(import.meta.url)('tailwindcss/colors');
const steps = [50,100,200,300,400,500,600,700,800,900,950];
if (manifest.schemaVersion !== 1 || !Object.hasOwn(manifest.themes, manifest.defaultId)) throw new Error('Invalid theme manifest');
const themes = Object.entries(manifest.themes).map(([id, file]) => {
  if (file !== `palettes/${id}.json`) throw new Error('Theme file must match its ID');
  const theme = resolveTheme(read(file), modes);
  if (theme.id !== id) throw new Error('Theme ID mismatch');
  const surfaces = ['canvas','shell','surface','raised'];
  for (const foreground of ['textPrimary','textSecondary','textMuted','link','success','warning','danger','info']) {
    for (const background of surfaces) if (contrastRatio(theme.colors[foreground],theme.colors[background]) < 4.5) throw new Error(`${id}: ${foreground}/${background} contrast failed`);
  }
  if (contrastRatio('#FFFFFF',theme.colors.action) < 4.5 || contrastRatio('#FFFFFF',theme.colors.actionHover) < 4.5) throw new Error(`${id}: action label contrast failed`);
  for (const surface of surfaces) if (contrastRatio(theme.colors.focus, theme.colors[surface]) < 3) throw new Error(`${id}: focus contrast failed`);
  return theme;
});
const rgb = color => rgbChannels(color).replaceAll(',', '');
function variables(theme) {
  const vars = cssVariables(theme), c = theme.colors;
  for(const family of ['gray','slate','zinc','neutral','stone']) {
    for (const step of steps) {
      const lightRoles = {50:c.textPrimary,100:c.textPrimary,200:c.textPrimary,300:c.textSecondary,400:c.textSecondary,500:c.textMuted,600:c.textMuted,700:c.textSecondary,800:c.textPrimary,900:c.textPrimary,950:c.textPrimary};
      let color = theme.mode === 'light' ? lightRoles[step] : standard[family][step];
      if(theme.mode === 'dark' && family === 'gray') color = ({100:c.textPrimary,300:c.textSecondary,400:c.textSecondary,500:c.textMuted,600:c.textMuted})[step] ?? color;
      vars[`--c-${family}-${step}`] = rgb(color);
    }
  }
  for(const family of ['brand','violet','purple','indigo']) {
    for(const step of steps) {
      let color = theme.mode === 'light' ? (step <= 400 ? c.link : step===500 ? c.action : c.actionHover)
        : step <= 400 ? mixColor(c.link,'#FFFFFF',(400-step)/650) : step===500 ? c.accent : mixColor(c.action,'#000000',(step-600)/650);
      if(theme.id === 'alpha-violet' && family==='brand') color = ({50:'#FAF5FF',100:'#F3E8FF',200:'#DDD6FE',300:'#C4B5FD',400:'#A78BFA',500:'#8B5CF6',600:'#7C3AED',700:'#6D28D9'})[step] ?? color;
      vars[`--c-${family}-${step}`] = rgb(color);
    }
  }
  for(const family of ['blue','sky','cyan','teal','emerald','green','lime','amber','yellow','orange','red','rose','pink','fuchsia']) {
    for(const step of steps) vars[`--c-${family}-${step}`] = rgb(standard[family][theme.mode === 'dark' ? step : step <= 400 ? 800 : step <=600 ? 700 : step]);
  }
  for(const role of ['success','warning','danger','info']) {
    vars[`--ui-status-${role}`] = rgb(c[role]);
    vars[`--ui-status-${role}-subtle`] = rgb(mixColor(c.surface,c[role],theme.mode==='light'?.07:.1));
    vars[`--ui-status-${role}-border`] = rgb(mixColor(c.surface,c[role],.35));
  }
  return vars;
}
const block = theme => `  color-scheme: ${theme.mode};\n` + Object.entries(variables(theme)).map(([key,value])=>`  ${key}: ${value};`).join('\n');
const defaultTheme = themes.find(t=>t.id===manifest.defaultId);
const css = `/* Generated by npm run theme:generate. Edit model/palettes/*.json, never this file. */\n@layer base {\n:root {\n${block(defaultTheme)}\n}\n${themes.map(theme=>`html[data-theme="${theme.id}"] {\n${block(theme)}\n}`).join('\n')}\n}\n`;
const native = {schemaVersion:1,defaultId:manifest.defaultId,themes:Object.fromEntries(themes.map(theme=>[theme.id,{id:theme.id,mode:theme.mode,canvas:theme.colors.canvas,shell:theme.colors.shell,symbol:theme.colors.textSecondary}]))};
// A classic head script runs before styles/React. The route test is intentionally conservative;
// public branded entry points never inherit an internal workspace appearance preference.
const startup = `/* Generated theme startup. */\n(function(){var ids=${JSON.stringify(themes.map(t=>t.id))},fallback=${JSON.stringify(manifest.defaultId)},key='alpha.appearance.v1',id=fallback;try{var bridge=window.alphaDesktop,loc=window.location,p=loc.pathname,h=(loc.hash||'').split('?')[0],q=new URLSearchParams(loc.search||''),publicEntry=!bridge&&((!q.has('code')&&!q.has('ticketing-preview')&&p==='/'&&(!h||/^#\\/(home)?$/.test(h)))||/^\\/(client\\/(forgot|activate)|request)(\\/|$)/.test(p)||/^#\\/(client\\/(forgot|activate)|request)(\\/|$)/.test(h));if(!publicEntry){var raw=bridge&&bridge.appearanceThemeId;if(!raw){var pref=JSON.parse(localStorage.getItem(key)||'null');raw=pref&&pref.version===1?pref.themeId:null;}if(ids.indexOf(raw)!==-1)id=raw;}}catch(e){}var root=document.documentElement;root.dataset.theme=id;var light=${JSON.stringify(themes.filter(t=>t.mode==='light').map(t=>t.id))}.indexOf(id)!==-1;root.classList.toggle('dark',!light);root.style.colorScheme=light?'light':'dark';})();\n`;
const outputs = new Map([
  ['src/shared/theme/generated/themes.css',css],
  ['public/theme-manifest.json',JSON.stringify(native,null,2)+'\n'],
  ['public/theme-startup.js',startup],
]);
for(const [name,value] of outputs) {
  const file=path.join(root,name);
  if(process.argv.includes('--check')) {if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==value)throw new Error(`Stale theme output: ${name}. Run npm run theme:generate`);}
  else {fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,value);}
}
console.log(`${process.argv.includes('--check')?'Checked':'Generated'} ${themes.length} themes; palette and contrast validation passed.`);
