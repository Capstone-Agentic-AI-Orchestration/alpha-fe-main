// Isolated browser rehearsal of the six UI changes. All API/provider traffic is mocked.
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const [modulePath, target, output, executable] = process.argv.slice(2);
const origin = new URL(target);
if (!['localhost', '127.0.0.1'].includes(origin.hostname)) throw new Error('Use a loopback test server.');
const { chromium } = await import(pathToFileURL(resolve(modulePath)).href);
const browser = await chromium.launch({ headless: true, executablePath: executable });
const context = await browser.newContext({ viewport: { width: 1366, height: 768 }, reducedMotion: 'reduce' });
const faults = [], requests = [], checks = [];
const stamp = '2026-10-16T00:00:00Z';
const agent = { id: 'agent-review', name: 'Code reviewer', role: 'Reviewer', avatar: '', color: '#8b5cf6', description: 'Reviews changes', modelProvider: 'OpenAI', runtimeId: 'codex', modelName: 'model-first', systemPrompt: 'Review code', autonomyLevel: 'supervised', temperature: 0.7, skills: [], stats: {}, status: 'idle', isArchived: false };
const squad = { id: 'squad-delivery', name: 'Delivery squad', topology: 'sequential', memberAgentIds: [agent.id], leaderAgentId: agent.id, mission: 'Deliver', avatar: '', color: '#8b5cf6' };
const project = { id: 'project-portal', name: 'Customer portal', key: 'PORT', description: 'A better customer experience', icon: '◆', color: '#8b5cf6', status: 'planned', priority: 'medium', targetDate: '', resources: [], leadAgentId: agent.id, leadName: agent.name, createdBy: 'ui-test', createdAt: stamp };
const issue = { id: 'issue-review', identifier: 'PORT-101', title: 'Review account settings', description: 'Check accessibility and empty states.', status: 'todo', priority: 'medium', projectId: project.id, assignedAgentId: agent.id, labels: [], subtasks: [], comments: [], createdAt: stamp, updatedAt: stamp };
const runtimes = [{ id: 'codex', name: 'OpenAI Codex CLI', provider: 'OpenAI', status: 'online', type: 'cloud', latencyMs: 22, isDefault: true, models: ['model-first', 'model-selected'] }];
const thread = { id: 'thread-portal', projectId: project.id, title: 'Portal planning', ownerId: 'ui-test', lastMessageAt: stamp, messages: Array.from({ length: 18 }, (_, index) => ({ id: `message-${index}`, senderType: index % 2 ? 'agent' : 'user', senderName: index % 2 ? 'Alpha' : 'You', content: `Planning message ${index + 1}. Review account settings, navigation, and accessibility before delivery.`, timestamp: stamp })) };
let projects = [project], issues = [issue], scannedEmpty = false;
let releaseChatReply, chatRequestSeen;
const replyGate = new Promise(resolve => { releaseChatReply = resolve; });
const chatRequested = new Promise(resolve => { chatRequestSeen = resolve; });
await context.addInitScript(() => {
  localStorage.setItem('alpha_multica_prototype_guide_complete', 'true');
  window.alphaDesktop = { isDesktop: true, platform: 'win32', apiBase: location.origin + '/api', versions: { electron: 'test', node: 'test', chrome: 'test' } };
  localStorage.setItem('alpha_multica_active_workspace_id', JSON.stringify('ui-workspace'));
  localStorage.setItem('alpha_multica_workspace_tabs_v3', JSON.stringify([{ id: 'test-projects', view: 'projects', sessionState: {} }]));
  localStorage.setItem('alpha_multica_active_tab_id_v3', JSON.stringify('test-projects'));
});
await context.route('**/*', async route => {
  const request = route.request(), url = new URL(request.url());
  if (url.pathname.startsWith('/api')) {
    requests.push({ path: url.pathname, method: request.method(), body: request.postDataJSON?.() });
    let body = [];
    if (url.pathname === '/api/me') body = { authenticated: true, login: 'ui-test', name: 'UI reviewer', source: 'github', role: 'pm', github: 'ok', access: 'granted', teams: [] };
    else if (url.pathname === '/api/workspaces') body = [{ id: 'ui-workspace', name: 'Alpha workspace', slug: 'alpha', role: 'pm' }];
    else if (url.pathname.endsWith('/members')) body = [{ id: 'member-test', userId: 'ui-test', role: 'pm', status: 'active' }];
    else if (url.pathname === '/api/health') body = { status: 'ok' };
    else if (url.pathname === '/api/projects' && request.method() === 'POST') { body = request.postDataJSON(); projects.push(body); }
    else if (/^\/api\/projects\/[^/]+$/.test(url.pathname) && request.method() === 'PUT') { projects = projects.map(item => item.id === url.pathname.split('/').at(-1) ? { ...item, ...request.postDataJSON() } : item); body = projects.find(item => item.id === url.pathname.split('/').at(-1)); }
    else if (url.pathname.endsWith('/checkouts')) body = { checkouts: [] };
    else if (url.pathname.endsWith('/binding')) body = null;
    else if (url.pathname.endsWith('/repos')) body = { repositories: [] };
    else if (url.pathname === '/api/projects') body = projects;
    else if (url.pathname === '/api/agents') body = [agent];
    else if (url.pathname === '/api/squads') body = [squad];
    else if (url.pathname === '/api/runtimes/scan') { scannedEmpty = true; body = []; }
    else if (url.pathname.startsWith('/api/runtimes')) body = scannedEmpty ? [] : runtimes;
    else if (url.pathname === '/api/issues') body = issues;
    else if (url.pathname === `/api/issues/${issue.id}` && request.method() === 'PUT') { issues = issues.map(item => item.id === issue.id ? { ...item, ...request.postDataJSON() } : item); body = issues[0]; }
    else if (url.pathname === '/api/chat/threads') body = [thread];
    else if (url.pathname.endsWith('/messages') && request.method() === 'GET') body = thread.messages;
    else if (url.pathname === '/api/chat/messages') { chatRequestSeen(); await replyGate; const input = request.postDataJSON(); body = { userMessage: { id: 'sent', content: input.content, senderType: 'user', senderName: 'You', timestamp: stamp }, agentMessage: { id: 'reply', content: 'The portal review is ready.', senderType: 'agent', senderName: 'Alpha', timestamp: stamp } }; }
    else if (url.pathname.endsWith('/chat/available-agents')) body = { project: { id: project.id, name: project.name, key: project.key, assignedSquadNames: [squad.name], workingCopy: { status: 'missing' } }, agents: [], squads: [] };
    else if (url.pathname === '/api/agents/builder/message') body = { content: 'A focused reviewer is ready. <agent_draft>{"name":"Portal reviewer"}</agent_draft>', runtimeId: 'codex', provider: 'OpenAI', modelName: request.postDataJSON().modelName };
    else if (url.pathname === '/api/analytics') body = {};
    return route.fulfill({ contentType: 'application/json', body: JSON.stringify(body) });
  }
  if (url.origin !== origin.origin) return route.abort();
  if (url.pathname === '/src/shared/lib/supabase.ts') return route.fulfill({ contentType: 'application/javascript', body: 'export const supabase = null; export const isSupabaseConfigured = () => false;' });
  return route.continue();
});
if (context.routeWebSocket) await context.routeWebSocket('**/*', socket => { const url = new URL(socket.url()); if (url.host === origin.host) socket.connectToServer(); else socket.close(); });
const page = await context.newPage();
page.on('pageerror', error => faults.push(error.message));
const shot = name => page.screenshot({ path: resolve(output, `${name}.png`), fullPage: true, animations: 'disabled' });
try {
  await mkdir(output, { recursive: true });
  await page.goto(target);
  await page.getByRole('button', { name: 'New project', exact: true }).waitFor();
  assert.equal(await page.getByText('Lead', { exact: true }).count(), 0);
  await shot('project-list-laptop');
  checks.push('Project list has no Lead column and remaining headers align');
  await page.getByRole('button', { name: 'New project', exact: true }).click();
  await page.getByLabel('Project name').fill('Customer insights');
  assert.equal(await page.getByRole('button', { name: 'Create project', exact: true }).isEnabled(), false);
  await page.getByLabel('Execution owner').selectOption('squad:squad-delivery');
  await page.getByLabel('Repository URL').fill('https://github.com/alpha/insights.git');
  await shot('project-create-laptop');
  assert.equal(await page.getByRole('button', { name: 'Create project', exact: true }).isEnabled(), true);
  await page.setViewportSize({ width: 480, height: 720 });
  await shot('project-create-narrow');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.getByRole('button', { name: 'Create project', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('[role="dialog"]'));
  const created = requests.find(request => request.method === 'POST' && request.path === '/api/projects').body;
  assert.equal(created.leadSquadId, squad.id);
  assert.equal(created.resources[0].pathOrUrl, 'https://github.com/alpha/insights');
  checks.push('Required ownership; typed repository included on create; laptop/narrow layout');
  await page.getByTitle('Edit Project Details', { exact: true }).click();
  await page.getByLabel('Execution owner').selectOption('agent:agent-review');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('alpha_multica_projects:ui-workspace'))[0].leadAgentId === 'agent-review');
  checks.push('Project settings uses the same agent-or-squad owner control and saves the new owner');
  await page.setViewportSize({ width: 1366, height: 768 });
  const sidebar = page.getByRole('complementary', { name: 'Application sidebar' });
  const agentsNav = sidebar.getByRole('button', { name: 'Agents', exact: true });
  await agentsNav.focus();
  await agentsNav.press('Enter');
  await page.getByRole('button', { name: /New agent|Hire agent/i }).first().click();
  await page.getByRole('button', { name: /Build with AI/i }).click();
  await page.getByLabel('Builder model').selectOption('model-selected');
  await shot('builder-model-laptop');
  await page.getByPlaceholder(/senior frontend reviewer/i).fill('An accessibility reviewer');
  await page.getByRole('button', { name: 'Start Building', exact: true }).click();
  await page.getByText('A focused reviewer is ready.').waitFor();
  assert.equal(requests.find(request => request.path === '/api/agents/builder/message').body.modelName, 'model-selected');
  const savedDraft = await page.evaluate(() => JSON.parse(localStorage.getItem('alpha_multica_agent_drafts')).byOwner.blank);
  assert.equal(savedDraft.builder.modelName, 'model-selected');
  assert.equal(savedDraft.draft.modelName, 'model-first');
  checks.push('Builder selected model forwarded and persisted independently of the target agent model');
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
  const chatNav = sidebar.getByRole('button', { name: 'Chat', exact: true });
  await chatNav.focus(); await chatNav.press('Enter');
  const threadButton = page.getByRole('button', { name: /Portal planning/ });
  await threadButton.focus(); await threadButton.press('Enter');
  const transcript = page.getByLabel('Conversation messages');
  await transcript.waitFor();
  const frame = () => page.evaluate(() => ({ documentTop: document.scrollingElement.scrollTop, main: document.querySelector('main').getBoundingClientRect().top }));
  const before = await frame();
  await transcript.evaluate(el => { el.scrollTop = 0; el.dispatchEvent(new Event('scroll')); });
  await page.getByPlaceholder('Ask Alpha about this project…').fill('Summarize our progress');
  await page.getByPlaceholder('Ask Alpha about this project…').press('Enter');
  await chatRequested;
  await transcript.evaluate(el => { el.scrollTop = 0; el.dispatchEvent(new Event('scroll')); });
  releaseChatReply();
  await page.getByText('The portal review is ready.', { exact: true }).waitFor();
  assert.equal(await transcript.evaluate(el => el.scrollTop), 0, 'Reply preserves reading position');
  await page.getByRole('button', { name: 'Jump to latest' }).click();
  assert.deepEqual(await frame(), before);
  await shot('chat-stable-laptop');
  checks.push('Sending/replying keeps the frame stable; reading history is preserved; Jump to latest works');
  const issuesNav = sidebar.getByRole('button', { name: 'All Issues', exact: true });
  await issuesNav.focus(); await issuesNav.press('Enter');
  await page.getByText('Review account settings', { exact: true }).first().click();
  const ownerControl = page.getByLabel('Assigned to', { exact: true });
  await ownerControl.selectOption('squad:squad-delivery');
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('alpha_multica_issues:ui-workspace'))[0].assignedSquadId === 'squad-delivery');
  await ownerControl.selectOption('');
  await page.waitForFunction(() => !JSON.parse(localStorage.getItem('alpha_multica_issues:ui-workspace'))[0].assignedSquadId);
  assert.equal(await page.getByText('Strategic Project', { exact: true }).count(), 0);
  await shot('issue-owner-laptop');
  checks.push('Issue has one owner control; squad and unassigned updates clear opposing fields');
  const runtimeNav = sidebar.getByRole('button', { name: 'Runtimes', exact: true });
  await runtimeNav.focus(); await runtimeNav.press('Enter');
  await page.getByRole('heading', { name: 'Runtimes', exact: true }).waitFor();
  assert.equal(await page.getByText('Ollama Local Engine', { exact: true }).count(), 0);
  assert.equal(await page.getByText('LM Studio Engine', { exact: true }).count(), 0);
  await shot('runtimes-detected-laptop');
  await page.getByRole('button', { name: 'Scan host engines', exact: true }).click();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('alpha_multica_runtimes')).length === 0);
  assert.equal(await page.getByText('OpenAI Codex CLI', { exact: true }).count(), 0);
  checks.push('Runtime page reflects detected engines; a successful empty scan clears old rows');
  assert.deepEqual(faults, []);
  await writeFile(resolve(output, 'results.json'), JSON.stringify({ checks, faults }, null, 2));
  console.log(JSON.stringify({ checks, faults }));
} catch (error) {
  await shot('failure');
  await writeFile(resolve(output, 'failure.txt'), `${error.stack}\n${await page.locator('body').innerText()}\n${JSON.stringify(faults)}\n${await page.evaluate(() => JSON.stringify(localStorage))}`);
  throw error;
} finally { await browser.close(); }
